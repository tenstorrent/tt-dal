#include "common.h"
#include <assert.h>
#include <ttdal.h>

// MARK: hardware
int main(void) {
    tt_session_t s;
    tt_session_t *sess = open_test_device(&s);
    if (!sess)
        return EXIT_FAILURE;
    // Successful open must produce a valid file descriptor
    assert(sess->fd >= 0);
    assert(tt_close(sess) == 0);
}
