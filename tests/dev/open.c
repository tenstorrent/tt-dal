#include "common.h"
#include <assert.h>
#include <ttdal.h>

// MARK: hardware
int main(void) {
    tt_device_t devs[1];
    tt_device_t *dev = open_test_device(devs);
    if (!dev)
        return EXIT_FAILURE;
    // Successful open must produce a valid file descriptor
    assert(dev->fd >= 0);
    tt_dev_close(dev);
}
